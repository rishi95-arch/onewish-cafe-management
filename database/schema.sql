CREATE TABLE IF NOT EXISTS users (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(100) NOT NULL, email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(60) NOT NULL, role ENUM('CUSTOMER','ADMIN') NOT NULL DEFAULT 'CUSTOMER',
 active BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS categories (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, slug VARCHAR(60) NOT NULL UNIQUE, name VARCHAR(80) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS menu_items (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(120) NOT NULL, description VARCHAR(1000) NOT NULL,
 price DECIMAL(10,2) NOT NULL CHECK(price >= 0), category_id BIGINT NOT NULL,
 image_url VARCHAR(500) NOT NULL, food_type ENUM('VEG','NON_VEG','EGG') NOT NULL DEFAULT 'VEG',
 available BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_menu_category FOREIGN KEY(category_id) REFERENCES categories(id), INDEX idx_menu_available_category(available,category_id), UNIQUE KEY uq_menu_name_category(name,category_id)
);
CREATE TABLE IF NOT EXISTS orders (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, reference VARCHAR(40) NOT NULL UNIQUE,
 customer_name VARCHAR(100) NOT NULL, phone VARCHAR(25) NOT NULL,
 fulfilment ENUM('pickup','delivery') NOT NULL, address VARCHAR(500) NULL,
 status ENUM('PLACED','PREPARING','READY','COMPLETED','CANCELLED') NOT NULL DEFAULT 'PLACED',
 total DECIMAL(10,2) NOT NULL CHECK(total >= 0), created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_orders_status_created(status,created_at)
);
CREATE TABLE IF NOT EXISTS order_items (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, order_id BIGINT NOT NULL, menu_item_id BIGINT NULL,
 item_name VARCHAR(120) NOT NULL, unit_price DECIMAL(10,2) NOT NULL, quantity INT NOT NULL CHECK(quantity BETWEEN 1 AND 20),
 CONSTRAINT fk_item_order FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE CASCADE,
 CONSTRAINT fk_item_menu FOREIGN KEY(menu_item_id) REFERENCES menu_items(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS contact_messages (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(100) NOT NULL, email VARCHAR(190) NOT NULL,
 message VARCHAR(2000) NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_contact_created(created_at)
);
